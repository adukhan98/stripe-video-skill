"""Scene projects for the designed moments: scaffold, re-install the runtime, render, verify.

Scenes are listed in <edit>/animations/scenes.json (written in the Build step, see SKILL.md):

    {"theme": "light", "look": "v7",
     "scenes": [
       {"id": "c01_map", "type": "map", "start": 41.233, "duration": 4.6, "hue": "blue",
        "assets": ["captures/stanford_2.png"], "brief": "..."},
       {"id": "o03_callout", "type": "callout_overlay", "start": 96.4, "duration": 2.2, "hue": "blue", "brief": "..."}]}

    start / duration are OUTPUT seconds (on the cut). Both are snapped to whole frames here; every render must be exactly
    that many frames. Types: canvas | map | board | proof (opaque, rendered .mp4, the card is composited over them later)
    and talk_overlay | callout_overlay (transparent, rendered .mov ProRes 4444, laid over talk/screen stretches).

    "look": "v7" (default) = the adnaan-reel v7 design system on the board runtime: board.css/js + v7yt.css/js +
    Phosphor icons (assets/icons), no marker layer — references/style.md. Colours come from the project's brand file
    (edit/brand/brand.json → brand.css, linked after v7yt.css in every scene by helpers/brand.py; Stripe by default).
    "greg" = the older Greg Light/Dark marker look
    (only when he asks for it). Talk captions over full-frame talk are generated by talkcaps.py, not hand-built.

    Rendering: always through `board.py render` (agents too: `board.py render --edit-dir E --only <id>`). It picks the
    right format (overlays MUST be ProRes 4444 .mov — an h264 .mov is opaque and the talk windows show paper instead of
    him) and holds one of YT_RENDER_SLOTS (default 6) machine-wide slots, so parallel agents queue instead of starving
    each other. Never `pkill` renders: other agents' renders die with yours.

Usage:
    python helpers/board.py prepare --edit-dir E [--only id,id]   # init + runtime + fonts + starter + assets + TASK.md
    python helpers/board.py runtime --edit-dir E                  # re-install board.css/js + marker.css/js everywhere
    python helpers/board.py render  --edit-dir E [--only ids] [--jobs 3]
    python helpers/board.py check   --edit-dir E                  # frame counts, sizes, alpha where expected
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brand  # noqa: E402  (the brand layer: edit/brand/brand.json → brand.css in every scene)

SKILL = Path(__file__).resolve().parent.parent
RUNTIME = SKILL / "templates" / "runtime"
STARTERS = SKILL / "templates" / "scenes"
FONTS = SKILL / "assets" / "fonts"
ICONS = SKILL / "assets" / "icons"
SLOTS = int(os.environ.get("YT_RENDER_SLOTS", "6"))
FPS = 30
OPAQUE = {"canvas", "map", "board", "proof"}
OVERLAY = {"talk_overlay", "callout_overlay"}
TYPES = OPAQUE | OVERLAY


def frames(seconds: float) -> int:
    return int(round(seconds * FPS))


def load(edit: Path) -> dict:
    p = edit / "animations" / "scenes.json"
    if not p.exists():
        sys.exit(f"no {p} — write the scene list first (SKILL.md, Build)")
    data = json.loads(p.read_text())
    data.setdefault("look", "v7")
    for s in data["scenes"]:
        if s["type"] not in TYPES:
            sys.exit(f"{s['id']}: unknown type {s['type']} (one of {sorted(TYPES)})")
        s["frames"] = frames(s["duration"])
        s["start_frame"] = frames(s["start"])
    return data


def pick(scenes: list[dict], only: str | None) -> list[dict]:
    if not only:
        return scenes
    ids = set(only.split(","))
    return [s for s in scenes if s["id"] in ids]


def install_runtime(hf: Path, look: str = "v7") -> None:
    for name in ("board.css", "board.js", "marker.css", "marker.js"):
        shutil.copy2(RUNTIME / name, hf / name)
    shutil.copytree(FONTS, hf / "fonts", dirs_exist_ok=True)
    if look == "v7":
        install_v7(hf)


def install_v7(hf: Path) -> None:
    """v7 MINT layer: v7yt.css/js after board.css/js, Phosphor icons, no marker layer (idempotent)."""
    for name in ("v7yt.css", "v7yt.js"):
        shutil.copy2(RUNTIME / name, hf / name)
    shutil.copytree(ICONS, hf / "assets" / "icons", dirs_exist_ok=True)
    p = hf / "index.html"
    if not p.exists():
        return
    h = p.read_text()
    h = re.sub(r'\s*<link rel="stylesheet" href="marker\.css" />', "", h)
    h = re.sub(r'\s*<script src="marker\.js"></script>', "", h)
    if "v7yt.css" not in h:
        h = h.replace('<link rel="stylesheet" href="board.css" />',
                      '<link rel="stylesheet" href="board.css" />\n    <link rel="stylesheet" href="v7yt.css" />')
    if "v7yt.js" not in h:
        h = h.replace('<script src="board.js"></script>', '<script src="board.js"></script>\n    <script src="v7yt.js"></script>')
    h = h.replace("const M = Marker.init(B);", "const V = V7Y.init(B);")
    h = "\n".join(l for l in h.split("\n") if not re.match(r"\s*M\.\w+\(", l))
    p.write_text(h)
    brand.install(hf)


V7_RULES = """
## v7 look on the project brand (references/style.md is binding, it OVERRIDES any older wording in the brief)

- hf/index.html loads board.js + **v7yt.js** (read its header: V.disc, V.discIn, V.chain, V.line, V.ringRect, V.ringCircle,
  V.bar, V.hl, V.check, V.cross, V.cam). No marker.js, no Caveat, no pastel tiles/hues, no yellow highlighter.
- Colours come ONLY from the brand tokens (hf/brand.css, generated from edit/brand/brand.json — never edit it, never type
  a hex): `var(--brand-primary)` is the ONE accent (current item, hero word `.mint`, rings, check discs; Stripe blurple),
  `var(--brand-deep)` carries discs, dark cards and ink (Stripe slate), `var(--strawberry)` is for DATA only (bars,
  result numbers, counters). V.mintTo / V.charcoalTo tween to those tokens. White Phosphor glyphs on deep discs
  (`hf/assets/icons/`; more: `$R/fetch.py icon --edit-dir <edit> <name>` then copy the svg in).
- Brief says marker loop → V.ringRect / V.ringCircle; underline → V.bar; arrow/bracket → V.line with a solid head;
  handwritten note → Inter Tight 800 label ≥ 44 px; tile → flat white card (`.v7-card`) or a deep disc; highlighter →
  V.hl; hatch → a flat mix of ink and paper; coin → deep disc with an Inter 700 number (accent when current).
- Frame 0 already shows the heading or the main object (entrances are fromTo with immediate render); no frame is bare paper.
- Opaque scenes: a WORLD on #cam bigger than the frame and a camera that travels (V.cam, x/y on different eases), one move
  per sentence. Labels sit on empty paper, never in a row of discs or over a neighbour.
"""


def task_md(s: dict, theme: str, d: Path, look: str = "v7") -> str:
    kind = "OPAQUE scene → render.mp4" if s["type"] in OPAQUE else "TRANSPARENT overlay → render.mov (ProRes 4444)"
    return f"""# Scene {s['id']} — {s['type']}

| | |
|---|---|
| Kind | {kind} |
| Frames | **exactly {s['frames']}** at {FPS} fps (data-duration = {s['frames'] / FPS:.3f}) |
| Output window | {s['start']:.3f}s → {s['start'] + s['frames'] / FPS:.3f}s of the cut |
| Theme / hue | {theme} / {s.get('hue', 'blue')} |
| Folder | `{d}` — work only here; scratch in `{d / 'qa'}` |

## Brief

{s.get('brief', '(none)')}

## Rules (references/style.md is binding)

- hf/index.html is the `{s['type']}` starter on the runtime (hf/board.js, hf/marker.js — read both headers). Keep the
  runtime untouched; write copy, positions and the bespoke object only.
- The speaker card is composited later over x 1574–1886, y 614–1012 (`<body data-debug>` shows it): nothing important there.
- Words on screen are only words he says (words in the brief). Real pages stay light; highlighter on the spoken phrase.
- Hero object + 1–3 micro-animations, motion on the spoken words, exits faster than entrances, no dead holds, no ghosted text.
- Text ≥ 34 px, kinetic hero ≥ 110 px; title-safe: everything inside x 96–1824, y 54–1026.
- Snapshot the landings first: `npx --yes hyperframes snapshot hf --at 1,2.5` (seconds) — render only when the stills are right.
- Check the count after rendering: `ffprobe -count_frames` must say {s['frames']} (`board.py check` does it for you).
- Write beats.json: [{{"t": seconds, "tag": "whoosh|paper|pop|thud|stamp", "role": "structural"}}] for at most 1–2 structural
  moments (a chapter landing, a big page sliding in). Most scenes have none.
- Render ONLY with `uv run --project ~/.claude/skills/adnaan-reel python ~/.claude/skills/stripe-youtube/helpers/board.py render
  --edit-dir {d.parent.parent} --only {s['id']}` (right format, shared render slots).
  Never pkill / killall renders — other scenes render on the same machine.
- Report: path, frame count, what the hero object does, deviations.
""" + (V7_RULES if look == "v7" else "")


def prepare(edit: Path, only: str | None) -> None:
    data = load(edit)
    theme = data.get("theme", "light")
    look = data["look"]
    root = edit / "animations"
    for s in pick(data["scenes"], only):
        d = root / s["id"]
        hf = d / "hf"
        d.mkdir(parents=True, exist_ok=True)
        (d / "qa").mkdir(exist_ok=True)
        if not (hf / "index.html").exists() or (hf / "index.html").read_text().find("Board.init") < 0:
            if not hf.exists():
                env = {**os.environ, "HYPERFRAMES_SKIP_SKILLS": "1"}
                subprocess.run(["npx", "--yes", "hyperframes", "init", "hf", "--example", "blank", "--non-interactive"],
                               cwd=d, env=env, check=True, capture_output=True)
            html = (STARTERS / f"{s['type']}.html").read_text()
            html = (html.replace("{{DURATION}}", f"{s['frames'] / FPS:.3f}")
                        .replace("{{THEME}}", theme).replace("{{HUE}}", s.get("hue", "blue")))
            (hf / "index.html").write_text(html)
        install_runtime(hf, look)
        (hf / "assets").mkdir(exist_ok=True)
        for a in s.get("assets", []):
            src = (edit / a) if not Path(a).is_absolute() else Path(a)
            if not src.exists():
                print(f"  ! {s['id']}: asset missing {src}")
                continue
            shutil.copy2(src, hf / "assets" / src.name)
        (d / "TASK.md").write_text(task_md(s, theme, d, look))
        (d / "slot.json").write_text(json.dumps(s, indent=1))
        print(f"{s['id']:24s} {s['type']:16s} {s['frames']:5d} f  → {d}")


def runtime(edit: Path) -> None:
    data = load(edit)
    for s in data["scenes"]:
        hf = edit / "animations" / s["id"] / "hf"
        if hf.exists():
            install_runtime(hf, data["look"])
            print("runtime →", hf)


def out_path(edit: Path, s: dict) -> Path:
    return edit / "animations" / s["id"] / ("render.mov" if s["type"] in OVERLAY else "render.mp4")


def probe(p: Path) -> dict:
    r = subprocess.run(["ffprobe", "-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries",
                        "stream=width,height,nb_read_frames,pix_fmt,r_frame_rate", "-of", "json", str(p)],
                       capture_output=True, text=True)
    st = json.loads(r.stdout or "{}").get("streams") or [{}]
    return st[0]


def slot(edit: Path):
    """A machine-wide render slot (lock dirs in animations/.slots): at most SLOTS renders at once across processes."""
    root = edit / "animations" / ".slots"
    root.mkdir(parents=True, exist_ok=True)
    while True:
        for i in range(1, SLOTS + 1):
            d = root / str(i)
            try:
                d.mkdir()
            except FileExistsError:
                owner = d / "pid"
                try:                                   # free a slot whose owner died
                    os.kill(int(owner.read_text()), 0)
                except ProcessLookupError:
                    shutil.rmtree(d, ignore_errors=True)
                except (ValueError, FileNotFoundError):    # being written right now, or a crash before the pid
                    if time.time() - d.stat().st_mtime > 30:
                        shutil.rmtree(d, ignore_errors=True)
                except PermissionError:
                    pass
                continue
            (d / "pid").write_text(str(os.getpid()))
            return d
        time.sleep(3)


def render_one(edit: Path, s: dict) -> str:
    hf = edit / "animations" / s["id"] / "hf"
    out = out_path(edit, s)
    cmd = ["npx", "--yes", "hyperframes", "render", ".", "-o", str(out), "--quiet"]
    if s["type"] in OVERLAY:
        cmd[4:4] = ["--format", "mov"]
    lock = slot(edit)
    try:
        r = subprocess.run(cmd, cwd=hf, capture_output=True, text=True)
    finally:
        shutil.rmtree(lock, ignore_errors=True)
    if r.returncode != 0:
        return f"{s['id']}: RENDER FAILED\n{r.stderr[-1500:]}"
    return check_one(edit, s)


def check_one(edit: Path, s: dict) -> str:
    p = out_path(edit, s)
    if not p.exists():
        return f"{s['id']}: missing {p.name}"
    st = probe(p)
    n = int(st.get("nb_read_frames", 0) or 0)
    bad = []
    if (st.get("width"), st.get("height")) != (1920, 1080):
        bad.append(f"size {st.get('width')}x{st.get('height')}")
    if n != s["frames"]:
        bad.append(f"{n} frames, expected {s['frames']}")
    if s["type"] in OVERLAY and "a" not in str(st.get("pix_fmt", "")):
        bad.append(f"no alpha ({st.get('pix_fmt')})")
    return f"{s['id']}: " + ("OK " + f"{n} f" if not bad else "PROBLEM " + "; ".join(bad))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["prepare", "runtime", "render", "check"])
    ap.add_argument("--edit-dir", required=True, type=Path)
    ap.add_argument("--only")
    ap.add_argument("--jobs", type=int, default=3)
    a = ap.parse_args()
    edit = a.edit_dir.resolve()
    if a.cmd == "prepare":
        prepare(edit, a.only)
    elif a.cmd == "runtime":
        runtime(edit)
    else:
        scenes = pick(load(edit)["scenes"], a.only)
        fn = render_one if a.cmd == "render" else check_one
        with ThreadPoolExecutor(max_workers=a.jobs if a.cmd == "render" else 8) as ex:
            for line in ex.map(lambda s: fn(edit, s), scenes):
                print(line)


if __name__ == "__main__":
    main()
